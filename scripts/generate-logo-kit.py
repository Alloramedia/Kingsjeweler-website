def build_zip():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    missing = [src for _, src in ASSETS if not os.path.exists(src)]
    if missing:
        print("WARNING — missing files (will be skipped):")
        for m in missing:
            print(f"  {m}")

    with zipfile.ZipFile(ZIP_PATH, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        # README
        zf.writestr(f"{ZIP_ROOT}/README.txt", README)

        # Assets
        for arc_path, src_path in ASSETS:
            if os.path.exists(src_path):
                zf.write(src_path, arc_path)
                size_kb = os.path.getsize(src_path) / 1024
                print(f"  + {arc_path}  ({size_kb:.0f} KB)")
            else:
                print(f"  - SKIPPED (not found): {arc_path}")

    zip_size = os.path.getsize(ZIP_PATH) / 1024
    print(f"\nLogo kit ZIP created: {ZIP_PATH}")
    print(f"Archive size: {zip_size:.0f} KB")

    # Print contents summary
    print("\nArchive contents:")
    with zipfile.ZipFile(ZIP_PATH, "r") as zf:
        for info in zf.infolist():
            print(f"  {info.filename}  ({info.file_size / 1024:.0f} KB)")


if __name__ == "__main__":
    build_zip()
