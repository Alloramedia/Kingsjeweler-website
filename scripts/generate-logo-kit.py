#!/usr/bin/env python3
"""
Pit & Masa — Logo & Icon Kit packager
========================================
Assembles all Pit & Masa brand logo and icon assets from the site into a
neatly-organised ZIP archive ready for download.

Output: pit-masa/public/resources/downloads/pit-masa-logo-kit.zip

Folder structure inside the ZIP:
  Pit-Masa-Logo-Kit/
    README.txt
    Primary-Logo/
      pit-masa-logo-white.png        (586 x 626 — full-resolution primary logo)
    Circle-Mark/
      pit-masa-logo-circle.png       (928 x 928 — standalone icon / avatar mark)
    Favicons/
      favicon.ico                    (multi-size ICO, generated by Next.js)
      favicon-192x192.png            (PWA / Android home-screen icon)
      favicon-512x512.png            (PWA splash / large icon)
      apple-touch-icon-180x180.png   (iOS home-screen icon)
    Social/
      og-image-1200x630.jpg          (Open Graph / social share image)
"""

import os
import shutil
import zipfile
import textwrap
from datetime import date

# ── Paths ─────────────────────────────────────────────────────────────
SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT   = os.path.join(SCRIPT_DIR, "..")
PUBLIC      = os.path.join(REPO_ROOT, "pit-masa", "public")
SRC_APP     = os.path.join(REPO_ROOT, "pit-masa", "src", "app")
OUTPUT_DIR  = os.path.join(PUBLIC, "resources", "downloads")
ZIP_NAME    = "pit-masa-logo-kit.zip"
ZIP_PATH    = os.path.join(OUTPUT_DIR, ZIP_NAME)
ZIP_ROOT    = "Pit-Masa-Logo-Kit"      # top-level folder inside the ZIP

# ── Asset manifest ─────────────────────────────────────────────
# (zip_path_inside_archive, source_file_path)
ASSETS = [
    # Primary logo
    (f"{ZIP_ROOT}/Primary-Logo/pit-masa-logo-white.png",
     os.path.join(PUBLIC, "images", "pit-masa-logo-white.png")),

    # Circle mark
    (f"{ZIP_ROOT}/Circle-Mark/pit-masa-logo-circle.png",
     os.path.join(PUBLIC, "images", "pit-masa-logo-circle.png")),

    # Favicons
    (f"{ZIP_ROOT}/Favicons/favicon.ico",
     os.path.join(SRC_APP, "favicon.ico")),
    (f"{ZIP_ROOT}/Favicons/favicon-192x192.png",
     os.path.join(PUBLIC, "icon.png")),
    (f"{ZIP_ROOT}/Favicons/favicon-512x512.png",
     os.path.join(PUBLIC, "icon-512.png")),
    (f"{ZIP_ROOT}/Favicons/apple-touch-icon-180x180.png",
     os.path.join(PUBLIC, "apple-icon.png")),

    # Social
    (f"{ZIP_ROOT}/Social/og-image-1200x630.jpg",
     os.path.join(PUBLIC, "og-image.jpg")),
]

# ── README content ────────────────────────────────────────────────────
